"""Build the Kaggle job that benchmarks Muse Glimmer 30B on two free T4 GPUs.

Packs the agent code, the vulnerable service and the benchmark into one script
(Kaggle runs a single file), then:
  python benchmark/kaggle/make_kernel.py
  kaggle kernels push -p benchmark/kaggle/build --accelerator NvidiaTeslaT4
  kaggle kernels output <id> -p benchmark/results/glimmer
"""
import base64
import io
import json
import sys
import tarfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BUILD = Path(__file__).resolve().parent / "build"
KERNEL_ID = sys.argv[1] if len(sys.argv) > 1 else "copyninja02/ooda-aegis-glimmer-benchmark"
TRIALS = 3

buf = io.BytesIO()
with tarfile.open(fileobj=buf, mode="w:gz") as tar:
    for rel in ["infrastructure/agent/aegis", "infrastructure/app", "benchmark/run_benchmark.py"]:
        tar.add(ROOT / rel, arcname=rel,
                filter=lambda ti: None if "__pycache__" in ti.name or ti.name.endswith(".pyc") else ti)
bundle = base64.b64encode(buf.getvalue()).decode()

script = f'''"""OODA-Aegis: Muse Glimmer 30B defense benchmark on Kaggle (2x T4).

Generated by benchmark/kaggle/make_kernel.py. Starts Meta's official 4-bit
Muse Glimmer 30B GGUF with llama.cpp, then runs benchmark/run_benchmark.py with
Glimmer as both the edge and the repair model. Results land in
/kaggle/working/glimmer_results.jsonl.
"""
import base64, glob, io, os, subprocess, sys, tarfile, time, urllib.request

REPO = "meta-models/Muse-Glimmer-30B-GGUF"
MODEL_FILE = "Muse-Glimmer-30B-KQuant-17GB-Q4_K_M.gguf"
URL = "http://127.0.0.1:8080"
BUNDLE = "{bundle}"


def sh(cmd):
    print("$", cmd, flush=True)
    subprocess.run(cmd, shell=True, check=True)


def start_glimmer():
    sh("nvidia-smi --query-gpu=name,memory.total --format=csv")
    saved = glob.glob("/kaggle/input/**/llama_bin.tgz", recursive=True)
    if not saved:
        raise SystemExit("attach the dataset with the prebuilt llama.cpp (llama_bin.tgz)")
    sh(f"mkdir -p /tmp/llama/build && tar -xzf {{saved[0]}} -C /tmp/llama/build")
    sh("pip install -q -U huggingface_hub")
    from huggingface_hub import hf_hub_download
    model = hf_hub_download(REPO, MODEL_FILE, local_dir="/tmp/models")
    log = open("/kaggle/working/llama_server.log", "w")
    subprocess.Popen(
        ["/tmp/llama/build/bin/llama-server", "-m", model, "-ngl", "99", "-c", "36864", "-np", "3",
         "--port", "8080", "--jinja", "--split-mode", "layer", "--alias", "muse-glimmer-30b"],
        stdout=log, stderr=subprocess.STDOUT,
        env={{**os.environ, "LD_LIBRARY_PATH": "/tmp/llama/build/bin:" + os.environ.get("LD_LIBRARY_PATH", "")}})
    for _ in range(240):
        try:
            if urllib.request.urlopen(URL + "/health", timeout=5).status == 200:
                print("Glimmer server ready", flush=True)
                return
        except Exception:
            pass
        time.sleep(5)
    raise RuntimeError("llama-server did not start; see llama_server.log")


def main():
    start_glimmer()
    sh("pip install -q fastapi==0.115.6 httpx==0.28.1 pytest==8.3.4 pytest-timeout==2.3.1 redis==5.2.1 openai==1.59.7")
    tarfile.open(fileobj=io.BytesIO(base64.b64decode(BUNDLE)), mode="r:gz").extractall("/kaggle/working/aegis")
    env = {{**os.environ, "GLIMMER_BASE_URL": URL + "/v1", "GLIMMER_MODEL": "muse-glimmer-30b"}}
    subprocess.run([sys.executable, "/kaggle/working/aegis/benchmark/run_benchmark.py", "--trials", "{TRIALS}",
                    "--parallel", "3", "--out", "/kaggle/working/glimmer_results.jsonl"], env=env, check=False)
    sh("tail -5 /kaggle/working/llama_server.log || true")


main()
'''

BUILD.mkdir(parents=True, exist_ok=True)
(BUILD / "aegis_glimmer_bench.py").write_text(script)
(BUILD / "kernel-metadata.json").write_text(json.dumps({
    "id": KERNEL_ID,
    "title": "OODA-Aegis Glimmer Benchmark",
    "code_file": "aegis_glimmer_bench.py",
    "language": "python",
    "kernel_type": "script",
    "is_private": True,
    "enable_gpu": True,
    "enable_internet": True,
    "dataset_sources": ["copyninja02/tula-llama-bin"],
    "competition_sources": [],
    "kernel_sources": [],
}, indent=2))
print(f"wrote {BUILD} ({len(script) // 1024} KB)")
